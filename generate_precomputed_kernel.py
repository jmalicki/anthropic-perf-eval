#!/usr/bin/env python3
"""
Generate a precomputed kernel file with optimized schedule.

This script:
1. Builds the kernel using InterleavedUnrolledKernelBuilder
2. Runs CP-SAT optimization to find the best schedule
3. Outputs solver/precomputed_kernel.py with the precomputed instructions

Usage:
    python generate_precomputed_kernel.py [--full-solve-time SECONDS]
"""

import argparse
import sys
from datetime import datetime


def generate_precomputed_kernel(
    forest_height: int = 10,
    n_nodes: int = 1023,
    batch_size: int = 128,
    rounds: int = 8,
    full_solve_time: float = 1800.0,
    output_file: str = "solver/precomputed_kernel.py"
):
    """Generate the precomputed kernel file."""

    print(f"=" * 60)
    print(f"Generating precomputed kernel")
    print(f"=" * 60)
    print(f"Parameters:")
    print(f"  forest_height: {forest_height}")
    print(f"  n_nodes: {n_nodes}")
    print(f"  batch_size: {batch_size}")
    print(f"  rounds: {rounds}")
    print(f"  full_solve_time: {full_solve_time}s")
    print()

    # Import here to avoid issues if dependencies aren't installed
    from solver.interleaved_unrolled_kernel import InterleavedUnrolledKernelBuilder

    # Build the kernel
    print("Building kernel...")
    builder = InterleavedUnrolledKernelBuilder()
    builder.build_kernel(forest_height, n_nodes, batch_size, rounds,
                        full_solve_time=full_solve_time)

    # Get the results
    instrs = builder.instrs
    scratch_ptr = builder.scratch_ptr
    scratch_debug = builder.scratch_debug

    # Calculate cycles (subtract 2 for pause instructions)
    num_cycles = len(instrs) - 2 if len(instrs) > 2 else len(instrs)

    print()
    print(f"Results:")
    print(f"  Instructions: {len(instrs)}")
    print(f"  Cycles: {num_cycles}")
    print(f"  Scratch usage: {scratch_ptr}")
    print(f"  Speedup: {147734 / num_cycles:.1f}x")
    print()

    # Generate the output file
    print(f"Writing {output_file}...")

    # Convert instructions to a format that can be written as Python code
    def format_instr(instr):
        """Format a single instruction as Python dict literal."""
        parts = []
        for engine, slots in sorted(instr.items()):
            formatted_slots = []
            for slot in slots:
                if isinstance(slot, (list, tuple)):
                    formatted_slots.append(repr(tuple(slot)))
                else:
                    formatted_slots.append(repr(slot))
            parts.append(f"'{engine}': [{', '.join(formatted_slots)}]")
        return "{" + ", ".join(parts) + "}"

    # Format scratch_debug
    def format_scratch_debug(sd):
        parts = []
        for addr, (name, length) in sorted(sd.items()):
            parts.append(f"    {addr}: ({repr(name)}, {length})")
        return "{\n" + ",\n".join(parts) + "\n}"

    with open(output_file, 'w') as f:
        f.write(f'''"""
Precomputed optimized kernel.

Generated by generate_precomputed_kernel.py on {datetime.now().isoformat()}

DO NOT EDIT MANUALLY - regenerate using:
    python generate_precomputed_kernel.py

Parameters used:
    forest_height={forest_height}
    n_nodes={n_nodes}
    batch_size={batch_size}
    rounds={rounds}
    full_solve_time={full_solve_time}

Results:
    cycles={num_cycles}
    speedup={147734 / num_cycles:.1f}x
"""

from problem import DebugInfo


# Expected parameters (asserted at runtime)
EXPECTED_PARAMS = {{
    'forest_height': {forest_height},
    'n_nodes': {n_nodes},
    'batch_size': {batch_size},
    'rounds': {rounds},
}}

# Precomputed scratch mapping
SCRATCH_PTR = {scratch_ptr}
SCRATCH_DEBUG = {format_scratch_debug(scratch_debug)}

# Precomputed instructions ({len(instrs)} total, {num_cycles} cycles)
INSTRUCTIONS = [
''')

        # Write instructions one per line for readability
        for i, instr in enumerate(instrs):
            f.write(f"    {format_instr(instr)},\n")

        f.write(''']


class PrecomputedKernelBuilder:
    """
    Kernel builder that uses precomputed optimized instructions.

    This avoids re-running the expensive CP-SAT optimization every time.
    """

    def __init__(self):
        self.instrs = []
        self.scratch_ptr = SCRATCH_PTR
        self.scratch_debug = SCRATCH_DEBUG.copy()

    def debug_info(self):
        return DebugInfo(scratch_map=self.scratch_debug)

    def build_kernel(self, forest_height, n_nodes, batch_size, rounds):
        """
        Build the kernel using precomputed instructions.

        Asserts that parameters match the precomputed values.
        """
        # Assert parameters match
        assert forest_height == EXPECTED_PARAMS['forest_height'], \\
            f"Expected forest_height={EXPECTED_PARAMS['forest_height']}, got {forest_height}"
        assert n_nodes == EXPECTED_PARAMS['n_nodes'], \\
            f"Expected n_nodes={EXPECTED_PARAMS['n_nodes']}, got {n_nodes}"
        assert batch_size == EXPECTED_PARAMS['batch_size'], \\
            f"Expected batch_size={EXPECTED_PARAMS['batch_size']}, got {batch_size}"
        assert rounds == EXPECTED_PARAMS['rounds'], \\
            f"Expected rounds={EXPECTED_PARAMS['rounds']}, got {rounds}"

        # Use precomputed instructions
        self.instrs = list(INSTRUCTIONS)

        return self
''')

    print(f"Done! Generated {output_file}")
    print()
    print(f"To use the precomputed kernel:")
    print(f"  from solver.precomputed_kernel import PrecomputedKernelBuilder")
    print(f"  builder = PrecomputedKernelBuilder()")
    print(f"  builder.build_kernel({forest_height}, {n_nodes}, {batch_size}, {rounds})")


def main():
    parser = argparse.ArgumentParser(description="Generate precomputed kernel")
    parser.add_argument("--forest-height", type=int, default=10)
    parser.add_argument("--n-nodes", type=int, default=1023)
    parser.add_argument("--batch-size", type=int, default=128)
    parser.add_argument("--rounds", type=int, default=8)
    parser.add_argument("--full-solve-time", type=float, default=1800.0,
                        help="Time limit for CP-SAT full solve in seconds (default: 1800)")
    parser.add_argument("--output", type=str, default="solver/precomputed_kernel.py",
                        help="Output file path")

    args = parser.parse_args()

    generate_precomputed_kernel(
        forest_height=args.forest_height,
        n_nodes=args.n_nodes,
        batch_size=args.batch_size,
        rounds=args.rounds,
        full_solve_time=args.full_solve_time,
        output_file=args.output,
    )


if __name__ == "__main__":
    main()
